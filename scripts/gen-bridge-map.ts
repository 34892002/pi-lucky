/**
 * Generate the renderer-side method → channel map from pi-gui's preload.
 *
 * pi-gui's preload is the authority on "which channel does `piApp.foo()` hit", so
 * rather than re-typing 100+ mappings (and drifting), we derive them from the
 * source we already ported. Re-run after syncing new preload changes.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dir, "..");
const preloadPath = path.join(repoRoot, "apps/desktop/reference/preload.ts");
const outPath = path.join(repoRoot, "apps/desktop/src/host/generated/bridge-map.ts");

const source = readFileSync(preloadPath, "utf8");
const lines = source.split("\n");

export interface BridgeEntry {
  readonly method: string;
  readonly channel: string;
  readonly kind: "invoke" | "subscribe" | "send";
}

const entries = new Map<string, BridgeEntry>();

/** Walk backwards to the `  methodName: ...` property that owns this line. */
function enclosingMethodName(lineIndex: number): string | null {
  for (let cursor = lineIndex; cursor >= 0; cursor -= 1) {
    const line = lines[cursor] ?? "";
    const match = /^ {2}([A-Za-z_$][\w$]*):/.exec(line);
    if (match?.[1]) {
      return match[1];
    }
  }
  return null;
}

function lineIndexAt(offset: number): number {
  let count = 0;
  for (let cursor = 0; cursor < offset; cursor += 1) {
    if (source.charCodeAt(cursor) === 10) {
      count += 1;
    }
  }
  return count;
}

/**
 * Multi-line calls are the norm here (`ipcRenderer.invoke(\n  desktopIpc.foo,\n ...)`),
 * so scan the whole file instead of line by line.
 */
const callPattern = /(ipcRenderer\.invoke|ipcRenderer\.send|subscribeIpc|ipcRenderer\.on)\(\s*(desktopIpc\.(\w+))/g;
for (const match of source.matchAll(callPattern)) {
  const call = match[1] ?? "";
  const channelKey = match[3] ?? "";
  const method = enclosingMethodName(lineIndexAt(match.index ?? 0));
  if (!method || !channelKey) {
    continue;
  }
  const kind: BridgeEntry["kind"] =
    call === "ipcRenderer.send"
      ? "send"
      : call === "subscribeIpc" || call === "ipcRenderer.on"
        ? "subscribe"
        : "invoke";
  const existing = entries.get(method);
  // A method may both invoke and subscribe; keep the invoke edge, add the rest later.
  if (!existing) {
    entries.set(method, { method, channel: channelKey, kind });
  }
}

const sorted = [...entries.values()].sort((left, right) => left.method.localeCompare(right.method));

const body = sorted
  .map((entry) => `  ${entry.method}: ["${entry.channel}", "${entry.kind}"],`)
  .join("\n");

const output = `// Generated by scripts/gen-bridge-map.ts — do not edit by hand.
// Source of truth: apps/desktop/reference/preload.ts (pi-gui, MIT).

export type BridgeCallKind = "invoke" | "subscribe" | "send";

/** \`piApp.<method>\` → \`[desktopIpc key, transport kind]\`. */
export const BRIDGE_METHODS = {
${body}
} as const satisfies Record<string, readonly [string, BridgeCallKind]>;

export type BridgeMethodName = keyof typeof BRIDGE_METHODS;
`;

mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, output);
console.log(`[gen-bridge-map] wrote ${sorted.length} methods → ${path.relative(repoRoot, outPath)}`);
